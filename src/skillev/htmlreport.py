"""Self-contained HTML report for a run (--html)."""
from __future__ import annotations

import html
from typing import Optional

from .runner import SuiteResult

_GRADE_COLOR = {"A": "#16a34a", "B": "#2563eb", "C": "#d97706", "D": "#dc2626"}


def _check_rows(case) -> str:
    rows = []
    for c in case.checks:
        icon = "✓" if c.passed else "✗"
        color = "#16a34a" if c.passed else "#dc2626"
        detail = html.escape(c.detail) if c.detail else ""
        rows.append(
            f"<tr><td class='icon' style='color:{color}'>{icon}</td>"
            f"<td class='mono'>{html.escape(c.type)}</td>"
            f"<td>{detail}</td></tr>"
        )
    return "".join(rows) or "<tr><td colspan='3' class='muted'>no checks</td></tr>"


def _case_block(case, diff) -> str:
    color = _GRADE_COLOR.get(case.grade, "#64748b")
    badge = ""
    if diff is not None:
        if diff.status == "gate":
            badge = "<span class='pill fail'>REGRESSED</span>"
        elif diff.status == "warn":
            badge = "<span class='pill warn'>dropped 1</span>"
        elif diff.status == "new":
            badge = "<span class='pill new'>new</span>"
    transcript = html.escape(case.transcript or "(no transcript)")
    return (
        f"<details class='case {'failed' if case.score < 90 else ''}'>"
        f"<summary><span class='grade' style='background:{color}'>{case.grade}</span>"
        f"<span class='name'>{html.escape(case.case)}</span>"
        f"<span class='score'>{case.score:.1f}</span>{badge}</summary>"
        f"<table><tr><th></th><th>check</th><th>detail</th></tr>{_check_rows(case)}</table>"
        f"<details class='transcript'><summary>transcript</summary><pre>{transcript}</pre></details>"
        f"</details>"
    )


def render_html(
    result: SuiteResult, diffs: Optional[list], baseline_id: Optional[str]
) -> str:
    diff_map = {d.case: d for d in (diffs or [])}
    gate_failed = any(d.status == "gate" for d in diff_map.values())
    gate = (
        "<span class='pill fail'>regression gate: FAIL</span>"
        if gate_failed
        else ("<span class='pill pass'>regression gate: PASS</span>" if diffs is not None else "")
    )
    baseline = f" vs <code>{html.escape(baseline_id)}</code>" if baseline_id else ""
    cases_html = "".join(_case_block(c, diff_map.get(c.case)) for c in result.cases)
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8">
<title>skill-eval report — {html.escape(result.skill)}</title>
<style>
:root {{ color-scheme: light; }}
body {{ font: 15px/1.5 -apple-system, "Segoe UI", sans-serif; color: #1e293b;
       max-width: 860px; margin: 24px auto; padding: 0 16px; }}
h1 {{ font-size: 22px; }} h1 .skill {{ color: #2563eb; }}
.meta {{ color: #64748b; font-size: 13px; margin-bottom: 20px; }}
.pill {{ padding: 2px 10px; border-radius: 999px; font-size: 12px; font-weight: 600; }}
.pill.pass {{ background: #dcfce7; color: #16a34a; }}
.pill.fail {{ background: #fee2e2; color: #dc2626; }}
.pill.warn {{ background: #fef3c7; color: #d97706; }}
.pill.new {{ background: #dbeafe; color: #2563eb; }}
details.case {{ border: 1px solid #e2e8f0; border-radius: 8px; margin: 8px 0; }}
details.case.failed {{ border-color: #fecaca; }}
details.case summary {{ display: flex; align-items: center; gap: 10px;
                        padding: 10px 14px; cursor: pointer; list-style: none; }}
details.case summary::-webkit-details-marker {{ display: none; }}
.grade {{ color: #fff; font-weight: 700; border-radius: 6px;
          width: 26px; text-align: center; padding: 2px 0; font-size: 14px; }}
.name {{ font-weight: 600; flex: 1; }}
.score {{ font-variant-numeric: tabular-nums; color: #475569; }}
table {{ width: 100%; border-collapse: collapse; padding: 0 14px 10px; margin: 0 0 4px 0; }}
th {{ text-align: left; font-size: 11px; text-transform: uppercase;
      letter-spacing: .05em; color: #94a3b8; padding: 4px 14px; }}
td {{ padding: 4px 14px; border-top: 1px solid #f1f5f9; vertical-align: top; }}
td.icon {{ width: 20px; font-weight: 700; }}
.mono {{ font-family: ui-monospace, Consolas, monospace; font-size: 13px; }}
.muted {{ color: #94a3b8; }}
details.transcript {{ margin: 0 14px 12px; }}
details.transcript summary {{ cursor: pointer; color: #2563eb; font-size: 13px; }}
details.transcript pre {{ background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px;
                          padding: 10px; font-size: 12px; overflow: auto; white-space: pre-wrap; }}
footer {{ margin-top: 24px; color: #94a3b8; font-size: 12px; }}
</style></head><body>
<h1><span class="skill">{html.escape(result.skill)}</span> — eval report</h1>
<div class="meta">run <code>{html.escape(result.run_id)}</code> · adapter {html.escape(result.adapter)}
{baseline} · avg score <b>{result.avg_score}</b> &nbsp; {gate}</div>
{cases_html}
<footer>generated by <a href="https://github.com/D0NO1/skill-eval">skill-eval</a></footer>
</body></html>"""
